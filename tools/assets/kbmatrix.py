#!/usr/bin/env python3
# turns a Swarm kb_matrix.xml (which key sits where on the picture and which led it has) into a table the library can compile in
# usage: tools/assets/kbmatrix.py KB_MATRIX.xml NAME > src/lib/keyboards/NAME.inc
# the xml has two sets of numbers per key and only one of them is the key: x/y/w/h, in pixels of the 1024x768 picture set
# (693x368 on the Ryos). the t_x/t_y/t_w/t_h next to them look like a bigger version but are just where the print goes,
# every key is 61x61 there (found that out the hard way, the first table had every key the same size).
# whatever picture the gui ends up drawing gets stretched onto the small coordinate space, all picture sets show the same thing.
# keys that arent rectangles (ISO enter, thumb keys) also have a <POLYGON> with their corners, the table only has the box for now
# regions without keys in the xml (Swarm has a few empty ones) are left out
import re, sys

# (polygons that ROCCAT commented out would otherwise still count)
xml = re.sub(r'<!--\s*<POLYGON.*?-->', '', open(sys.argv[1], encoding='utf-8-sig').read(), flags=re.S)
name = sys.argv[2]
print('// generated by tools/assets/kbmatrix.py from the %s kb_matrix.xml out of ROCCAT Swarm, dont edit by hand' % name.replace('_', ' '))
print('// name, led index, then x / y / width / height in pixels of the 1024x768 picture set')
regions = []
# most regions carry their name as a comment. the ones that dont: 1 is DE on every board we checked, the rest gets its number
GUESS = {'0': 'US', '1': 'DE'}
for m in re.finditer(r'<REGION value="(\d+)"[^>]*>\s*(?:<!--(\w+)-->)?(.*?)</REGION>', xml, re.S):
    value, body = int(m.group(1)), m.group(3)
    label = (m.group(2) or GUESS.get(m.group(1)) or 'R%d' % value).upper()
    keys = re.findall(r'<KEY name="([^"]*)" index="(\d+)"[^>]*?\sx="(-?\d+)" y="(-?\d+)" w="(\d+)" h="(\d+)"', body)
    if not keys:
        continue
    # the Horde AIMO has ES twice (16 and 18), the array names still have to be unique
    ident = label if label not in [r[3] for r in regions] else '%s_%d' % (label, value)
    regions.append((value, label, len(keys), ident))
    print('static const rockcat_key %s_%s[] = {' % (name, ident))
    for key, index, x, y, w, h in keys:
        text = key.replace('\\', '\\\\').replace('"', '\\"').replace('&lt;', '<').replace('&gt;', '>').replace('&amp;', '&')
        print('    {"%s", %s, %s, %s, %s, %s},' % (text, index, x, y, w, h))
    print('};')
print('static const keyboard_region %s_REGIONS[] = {' % name)
for value, label, count, ident in regions:
    print('    {%d, "%s", %s_%s, %d},' % (value, label, name, ident, count))
print('};')
